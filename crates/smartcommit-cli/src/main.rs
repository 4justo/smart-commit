//! SmartCommit CLI binary.
//!
//! Implements the five user-facing subcommands (`doctor`, `analyze`,
//! `plan`, `commit`, `restore`) and the shared preview pipeline that
//! `plan`, `commit --dry-run`, and `commit` all run through.
//!
//! Configuration (`.smartcommit.toml`) is loaded immediately after
//! repository discovery so that a broken config file is always caught
//! before any Git work begins. CLI flags take precedence over config
//! values, which take precedence over built-in defaults.

use clap::{Args, Parser, Subcommand};
use smartcommit_core::{
    build_commit_plan, create_safety_checkpoint, execute_commit_plan, execute_restore,
    get_staged_changes, get_staged_diffs, inspect_repository_state, load_config,
    manual_recovery_instructions, match_files_to_messages, plan_restore, save_operation_record,
    ChangeKind, CommitMessages, CommitPlan, ConfigError, DateTime, DiffLine, Duration,
    ExecutionReport, FileDiff, FixedOffset, InspectorError, OperationRecord, OperationRecordError,
    ParseCommitMessagesError, PlannedCommitTime, Repository, RepositoryError, RepositorySafety,
    RestoreError, RestorePlan, StagedChangesError, SystemRandomSource, TimelineMode, Utc,
};
use std::fs;
use std::io::Write;
use std::path::{Path, PathBuf};
use std::process::ExitCode;

/// Stage your changes, describe the commits you want, and let
/// SmartCommit split them safely — with a full preview, optional
/// timeline control, and a one-step undo if anything looks wrong.
#[derive(Parser, Debug)]
#[command(name = "smartcommit", version, about, long_about = None)]
#[command(arg_required_else_help = true)]
struct Cli {
    /// Path to operate on. Defaults to the current directory.
    /// Accepted anywhere along the repo-discovery path (repo root,
    /// or a directory nested inside it).
    #[arg(long, global = true, value_name = "PATH")]
    repo: Option<PathBuf>,

    #[command(subcommand)]
    command: Commands,
}

#[derive(Subcommand, Debug)]
enum Commands {
    /// Check repository detection and full state: branch, HEAD,
    /// in-progress merge/rebase/cherry-pick, conflicts, and
    /// staged/unstaged/untracked status.
    Doctor,
    /// List currently staged files, their change kind, and a diff
    /// summary (or full hunk content with --verbose).
    Analyze {
        /// Print full hunk content (added/removed/context lines)
        /// for every non-binary file, not just the summary.
        #[arg(long)]
        verbose: bool,
    },
    /// Preview a commit plan from a messages file and the currently
    /// staged changes. Read-only — makes no Git modification.
    Plan {
        /// Path to a text file containing commit messages.
        #[arg(long, value_name = "FILE")]
        messages_file: PathBuf,

        #[command(flatten)]
        timeline: TimelineArgs,
    },
    /// Build a commit plan and, after confirmation, create the
    /// commits for real.
    Commit {
        /// Path to a text file containing commit messages.
        #[arg(long, value_name = "FILE")]
        messages_file: PathBuf,

        #[command(flatten)]
        timeline: TimelineArgs,

        /// Skip the confirmation prompt and create the commits
        /// immediately.
        #[arg(long)]
        yes: bool,

        /// Perform every validation and planning step, and show the
        /// full preview, but make no Git modification.
        #[arg(long)]
        dry_run: bool,
    },
    /// Undo the most recent SmartCommit operation, using the safety
    /// checkpoint recorded before it ran. Refuses automatically if
    /// anything has happened since that makes restoring unsafe.
    Restore {
        /// Skip the confirmation prompt.
        #[arg(long)]
        yes: bool,
    },
}

/// Timeline options shared by `plan` and `commit`, so the preview
/// they show is generated by identical code either way —
/// `ARCHITECTURE.md` §36: "The same planning code should be used for
/// dry-run and real execution," extended here to cover preview too,
/// since all three paths (`plan`, `commit --dry-run`, `commit`) are
/// really the same pipeline diverging only after the preview step.
#[derive(Args, Debug, Clone)]
struct TimelineArgs {
    /// Custom start time for the first commit (RFC3339, e.g.
    /// 2026-09-01T09:00:00+03:00). If omitted, the *last* commit is
    /// anchored at the current time and earlier commits are placed
    /// backward — this can never produce a future timestamp.
    #[arg(long, value_name = "RFC3339")]
    start: Option<String>,

    /// Fixed interval, in minutes, between consecutive commits.
    /// Ignored if --random-min-minutes/--random-max-minutes are
    /// given. When omitted, the value from `.smartcommit.toml`
    /// (or the built-in default of 10) is used instead.
    #[arg(long, value_name = "MINUTES")]
    interval_minutes: Option<i64>,

    /// Minimum random interval, in minutes, between consecutive
    /// commits. Must be given together with --random-max-minutes.
    #[arg(long, value_name = "MINUTES")]
    random_min_minutes: Option<i64>,

    /// Maximum random interval, in minutes, between consecutive
    /// commits. Must be given together with --random-min-minutes.
    #[arg(long, value_name = "MINUTES")]
    random_max_minutes: Option<i64>,

    /// Allow generated timestamps to be later than the current time.
    /// Only relevant with --start close enough to now that a later
    /// commit would otherwise land in the future.
    #[arg(long)]
    allow_future: bool,
}

impl TimelineArgs {
    /// Resolves the `TimelineMode` for this invocation, applying the
    /// documented resolution order: CLI flags > config > built-in default.
    ///
    /// `config` is the `TimelineConfig` loaded from `.smartcommit.toml`
    /// (already containing built-in defaults for any absent fields).
    ///
    /// # Resolution logic
    ///
    /// - If `--random-min-minutes` AND `--random-max-minutes` are both
    ///   given on the CLI → random mode, CLI values used, config ignored.
    /// - Else if only one random flag is given → error (must be paired).
    /// - Else if `--interval-minutes` is given on the CLI → fixed mode,
    ///   CLI value used.
    /// - Else if config has both `random_min_minutes` and
    ///   `random_max_minutes` set → random mode, config values used.
    /// - Else → fixed mode, `config.gap_minutes` used (which is itself
    ///   either the config file value or the built-in default of 10).
    fn mode(&self, config: &smartcommit_core::TimelineConfig) -> Result<TimelineMode, ExitCode> {
        match (self.random_min_minutes, self.random_max_minutes) {
            // Both CLI random flags given — use them, ignore config.
            (Some(min), Some(max)) => Ok(TimelineMode::Random {
                min: Duration::minutes(min),
                max: Duration::minutes(max),
            }),
            // Only one CLI random flag given — always an error.
            (Some(_), None) | (None, Some(_)) => {
                eprintln!("--random-min-minutes and --random-max-minutes must be given together.");
                Err(ExitCode::FAILURE)
            }
            // No CLI random flags — check whether the user set an explicit
            // fixed interval, then fall back to config.
            (None, None) => {
                if let Some(cli_gap) = self.interval_minutes {
                    // --interval-minutes given explicitly → fixed mode, CLI wins.
                    return Ok(TimelineMode::Fixed {
                        interval: Duration::minutes(cli_gap),
                    });
                }
                // No CLI interval either — use config. If config has a random
                // range configured, prefer that over fixed mode.
                match (config.random_min_minutes, config.random_max_minutes) {
                    (Some(min), Some(max)) => Ok(TimelineMode::Random {
                        min: Duration::minutes(min as i64),
                        max: Duration::minutes(max as i64),
                    }),
                    _ => Ok(TimelineMode::Fixed {
                        interval: Duration::minutes(config.gap_minutes as i64),
                    }),
                }
            }
        }
    }

    fn parsed_start(&self) -> Result<Option<DateTime<FixedOffset>>, ExitCode> {
        match &self.start {
            None => Ok(None),
            Some(s) => DateTime::parse_from_rfc3339(s).map(Some).map_err(|e| {
                eprintln!("Invalid --start value \"{s}\": {e}");
                eprintln!("Expected RFC3339, e.g. 2026-09-01T09:00:00+03:00");
                ExitCode::FAILURE
            }),
        }
    }
}

fn main() -> ExitCode {
    let cli = Cli::parse();

    match cli.command {
        Commands::Doctor => run_doctor(cli.repo),
        Commands::Analyze { verbose } => run_analyze(cli.repo, verbose),
        Commands::Plan {
            messages_file,
            timeline,
        } => run_plan(cli.repo, messages_file, timeline),
        Commands::Commit {
            messages_file,
            timeline,
            yes,
            dry_run,
        } => run_commit(cli.repo, messages_file, timeline, yes, dry_run),
        Commands::Restore { yes } => run_restore(cli.repo, yes),
    }
}

/// Resolves the target path: `--repo` if given, else the current
/// directory. Shared by every subcommand that operates on a
/// repository.
fn resolve_target(repo_path: Option<PathBuf>) -> Result<PathBuf, ExitCode> {
    match repo_path {
        Some(p) => Ok(p),
        None => std::env::current_dir().map_err(|e| {
            eprintln!("Could not determine the current directory: {e}");
            ExitCode::FAILURE
        }),
    }
}

fn run_doctor(repo_path: Option<PathBuf>) -> ExitCode {
    let target = match resolve_target(repo_path) {
        Ok(t) => t,
        Err(code) => return code,
    };

    match inspect_repository_state(&target) {
        Ok(state) => {
            println!("Repository: valid");
            println!(
                "Branch: {}",
                state.branch.as_deref().unwrap_or("(detached or unknown)")
            );
            println!("HEAD: {}", state.head.as_deref().unwrap_or("(unknown)"));
            println!();
            println!("Staged changes: {}", yes_no(state.has_staged_changes));
            println!("Unstaged changes: {}", yes_no(state.has_unstaged_changes));
            println!("Untracked files: {}", yes_no(state.has_untracked_files));
            println!();
            println!("State: {}", safety_label(state.safety()));
            ExitCode::SUCCESS
        }
        Err(e) => report_inspector_error(e),
    }
}

fn run_analyze(repo_path: Option<PathBuf>, verbose: bool) -> ExitCode {
    let target = match resolve_target(repo_path) {
        Ok(t) => t,
        Err(code) => return code,
    };

    let files = match get_staged_changes(&target) {
        Ok(files) if files.is_empty() => {
            println!("No staged changes found.");
            return ExitCode::FAILURE;
        }
        Ok(files) => files,
        Err(e) => return report_staged_changes_error(e),
    };

    // A diff-extraction failure shouldn't hide the file list we
    // already have from get_staged_changes — fall back to listing
    // files without diff stats rather than losing the whole
    // command's output over a secondary failure.
    let diffs = match get_staged_diffs(&target) {
        Ok(diffs) => diffs,
        Err(e) => {
            eprintln!("Warning: could not extract diff content ({e}); showing file list only.");
            Vec::new()
        }
    };

    println!("Staged changes: {}", files.len());
    println!();
    for file in &files {
        let label = match file.change_kind {
            ChangeKind::Added => "Added",
            ChangeKind::Modified => "Modified",
            ChangeKind::Deleted => "Deleted",
            ChangeKind::Renamed => "Renamed",
        };
        match (&file.change_kind, &file.old_path) {
            (ChangeKind::Renamed, Some(old)) => {
                println!("{label:<9} {} -> {}", old.display(), file.path.display());
            }
            _ => {
                println!("{label:<9} {}", file.path.display());
            }
        }

        if let Some(diff) = diffs.iter().find(|d| d.path == file.path) {
            print_diff_summary(diff, verbose);
        }
        println!();
    }

    ExitCode::SUCCESS
}

/// Everything needed to render a plan preview, gathered by the one
/// pipeline `plan`, `commit --dry-run`, and `commit` all share.
struct Preview {
    repo_root: PathBuf,
    branch: Option<String>,
    staged_file_count: usize,
    plan: CommitPlan,
    timestamps: Vec<PlannedCommitTime>,
    /// Whether the user (or their config) requires a confirmation prompt
    /// before commits are actually created. Stored here so `run_commit`
    /// can honour `commit.require_confirmation = false` from config
    /// without re-reading the file.
    require_confirmation: bool,
}

/// Runs the full preview pipeline in the order `ARCHITECTURE.md`
/// §34 documents: discover repository -> inspect state -> read
/// staged changes -> parse messages -> match changes -> build
/// CommitPlan -> generate timeline. This is the single shared
/// implementation used by `plan`, `commit --dry-run`, and `commit`,
/// per §36's requirement that "the same planning code should be used
/// for dry-run and real execution."
///
/// Configuration (Module 13) is loaded from `.smartcommit.toml` at
/// the repository root immediately after repository discovery. CLI
/// flags always take precedence over config values.
fn build_preview(
    repo_path: Option<PathBuf>,
    messages_file: &Path,
    timeline: &TimelineArgs,
    now: DateTime<FixedOffset>,
) -> Result<Preview, ExitCode> {
    let target = resolve_target(repo_path)?;

    let repo = Repository::discover(&target).map_err(report_repository_error)?;

    // Load config right after we know the repo root. A missing file is
    // not an error — defaults are returned silently. An invalid file is
    // always a hard error so the user knows their config is broken before
    // anything else happens.
    let config = load_config(&repo.root).map_err(|e| {
        match &e {
            ConfigError::Io(io_err) => {
                eprintln!("Could not read .smartcommit.toml: {io_err}");
            }
            ConfigError::Parse(msg) => {
                eprintln!("Could not parse .smartcommit.toml: {msg}");
            }
            ConfigError::Validation(msg) => {
                eprintln!("Invalid .smartcommit.toml: {msg}");
            }
        }
        ExitCode::FAILURE
    })?;

    let state = inspect_repository_state(&repo.root).map_err(report_inspector_error)?;

    if state.safety() == RepositorySafety::Blocked {
        eprintln!("Repository is not in a safe state to plan or commit.");
        eprintln!();
        if state.merge_in_progress {
            eprintln!("- a merge is in progress");
        }
        if state.rebase_in_progress {
            eprintln!("- a rebase is in progress");
        }
        if state.cherry_pick_in_progress {
            eprintln!("- a cherry-pick is in progress");
        }
        if state.has_conflicts {
            eprintln!("- there are unresolved conflicts");
        }
        eprintln!();
        eprintln!("Resolve this before using smartcommit.");
        return Err(ExitCode::FAILURE);
    }

    let files = match get_staged_changes(&repo.root) {
        Ok(files) if files.is_empty() => {
            println!("No staged changes found.");
            return Err(ExitCode::FAILURE);
        }
        Ok(files) => files,
        Err(e) => return Err(report_staged_changes_error(e)),
    };

    // Same fallback as `analyze`: a diff-extraction failure
    // shouldn't block planning — diff content only affects the
    // matcher's diff-keyword evidence, not filename/directory
    // evidence, so a plan without it is still useful.
    let diffs = match get_staged_diffs(&repo.root) {
        Ok(diffs) => diffs,
        Err(e) => {
            eprintln!(
                "Warning: could not extract diff content ({e}); matching on filenames and directories only."
            );
            Vec::new()
        }
    };

    let text = fs::read_to_string(messages_file).map_err(|err| {
        eprintln!(
            "Could not read messages file {}: {err}",
            messages_file.display()
        );
        ExitCode::FAILURE
    })?;
    let messages = text.parse::<CommitMessages>().map_err(|err| {
        let ParseCommitMessagesError::EmptyInput = err;
        eprintln!(
            "Could not parse commit messages from {}: message input is empty",
            messages_file.display()
        );
        ExitCode::FAILURE
    })?;

    let scores = match_files_to_messages(&messages.0, &files, &diffs);

    // Pass matching thresholds from config (which already incorporates
    // built-in defaults for any fields absent from the file).
    // CLI has no per-flag overrides for these today, so config is the
    // final word after the built-in default.
    let plan = build_commit_plan(
        &messages.0,
        &files,
        &scores,
        config.matching.minimum_confidence,
        config.matching.ambiguity_margin,
    );

    // timeline.mode() applies the resolution order: CLI flag (if given)
    // > config value > built-in default.
    let mode = timeline.mode(&config.timeline)?;
    let start = timeline.parsed_start()?;
    let mut rng = SystemRandomSource::new();
    let timestamps = smartcommit_core::generate_timeline(
        plan.groups.len(),
        mode,
        start,
        now,
        timeline.allow_future,
        &mut rng,
    )
    .map_err(|e| {
        eprintln!("Could not generate a commit timeline: {e}");
        ExitCode::FAILURE
    })?;

    Ok(Preview {
        repo_root: repo.root,
        branch: state.branch,
        staged_file_count: files.len(),
        plan,
        timestamps,
        require_confirmation: config.commit.require_confirmation,
    })
}

/// Matches modules.md's Module 11 worked example exactly: repo,
/// branch, staged file count, proposed commit count, each group with
/// its files/confidence/time, unassigned files, warnings.
fn render_preview(preview: &Preview) {
    println!("SMARTCOMMIT PLAN");
    println!();
    println!("Repository: {}", preview.repo_root.display());
    println!(
        "Branch: {}",
        preview.branch.as_deref().unwrap_or("(detached or unknown)")
    );
    println!();
    println!("{} staged files", preview.staged_file_count);
    let proposed = preview
        .plan
        .groups
        .iter()
        .filter(|g| !g.files.is_empty())
        .count();
    println!(
        "{} proposed commit{}",
        proposed,
        if proposed == 1 { "" } else { "s" }
    );
    println!();

    for (i, group) in preview.plan.groups.iter().enumerate() {
        println!("[{}] {}", i + 1, group.message);
        if group.files.is_empty() {
            println!("    (no matching files)");
        } else {
            for file in &group.files {
                println!("    {}", file.path.display());
            }
        }
        println!("    Confidence: {:.0}%", group.confidence * 100.0);
        if let Some(t) = preview.timestamps.iter().find(|t| t.commit_index == i) {
            println!("    Time: {}", t.timestamp.format("%H:%M"));
        }
        println!();
    }

    if !preview.plan.unassigned.is_empty() {
        println!("Unassigned:");
        for file in &preview.plan.unassigned {
            println!("    {}", file.path.display());
        }
        println!();
    }

    if !preview.plan.warnings.is_empty() {
        println!("Warnings:");
        for warning in &preview.plan.warnings {
            println!("    {warning}");
        }
    }
}

fn run_plan(
    repo_path: Option<PathBuf>,
    messages_file: PathBuf,
    timeline: TimelineArgs,
) -> ExitCode {
    let now: DateTime<FixedOffset> = Utc::now().into();
    let preview = match build_preview(repo_path, &messages_file, &timeline, now) {
        Ok(p) => p,
        Err(code) => return code,
    };

    render_preview(&preview);
    ExitCode::SUCCESS
}

fn run_commit(
    repo_path: Option<PathBuf>,
    messages_file: PathBuf,
    timeline: TimelineArgs,
    yes: bool,
    dry_run: bool,
) -> ExitCode {
    // Captured once and reused for both the timeline's `now` anchor
    // and the checkpoint's creation time, so a single invocation is
    // internally consistent about "now" throughout.
    let now_utc = Utc::now();
    let now: DateTime<FixedOffset> = now_utc.into();

    let preview = match build_preview(repo_path, &messages_file, &timeline, now) {
        Ok(p) => p,
        Err(code) => return code,
    };

    render_preview(&preview);

    let has_anything_to_commit = preview.plan.groups.iter().any(|g| !g.files.is_empty());
    if !has_anything_to_commit {
        println!();
        println!("Nothing to commit: no message has any matching files.");
        return ExitCode::FAILURE;
    }

    if dry_run {
        println!();
        println!("Dry run: no changes were made.");
        return ExitCode::SUCCESS;
    }

    // Resolution order for the confirmation prompt:
    //   --yes flag (highest priority) > config require_confirmation > built-in default (true)
    // If the user passed --yes, skip the prompt regardless of config.
    // If config sets require_confirmation = false, skip the prompt too.
    // Otherwise ask.
    let needs_prompt = !yes && preview.require_confirmation;
    if needs_prompt {
        print!("\nCreate these commits? [y/N] ");
        if std::io::stdout().flush().is_err() {
            // Non-fatal: proceed to read input anyway even if the
            // prompt itself didn't flush cleanly.
        }
        let mut input = String::new();
        if std::io::stdin().read_line(&mut input).is_err() {
            eprintln!("Could not read confirmation input.");
            return ExitCode::FAILURE;
        }
        let answer = input.trim().to_lowercase();
        if answer != "y" && answer != "yes" {
            println!("Cancelled.");
            return exit_code_cancelled();
        }
    }

    let checkpoint = match create_safety_checkpoint(&preview.repo_root, now_utc) {
        Ok(c) => c,
        Err(e) => {
            eprintln!("Could not create a safety checkpoint: {e}");
            eprintln!("Aborting — no commits were created.");
            return ExitCode::FAILURE;
        }
    };

    let report = match execute_commit_plan(
        &preview.repo_root,
        &preview.plan.groups,
        Some(&preview.timestamps),
        &checkpoint,
    ) {
        Ok(r) => r,
        Err(e) => {
            eprintln!("Could not execute the commit plan: {e}");
            eprintln!();
            eprintln!("Recovery checkpoint: {}", checkpoint.backup_ref);
            return ExitCode::FAILURE;
        }
    };

    // Recorded regardless of full success or partial failure — this
    // is what `smartcommit restore` reads later. If saving the
    // record itself fails, that's surfaced as a warning, not a
    // reason to treat the commits (which already exist for real) as
    // failed — restore just won't have anything to act on for this
    // run, and the checkpoint ref printed below still gives a manual
    // recovery path either way.
    let record = OperationRecord::from_execution(&checkpoint, &report, now_utc);
    if let Err(e) = save_operation_record(&preview.repo_root, &record) {
        eprintln!("Warning: could not save operation record ({e}); `smartcommit restore` will not see this operation.");
    }

    render_execution_report(&report);

    if report.is_full_success() {
        ExitCode::SUCCESS
    } else {
        exit_code_partial_failure()
    }
}

/// Matches modules.md's Module 12 "Safety" section: current HEAD,
/// checkpoint HEAD, branch, commits that would be removed, and
/// working-tree state — shown before any confirmation, safe or not.
fn render_restore_plan(plan: &RestorePlan) {
    println!("SMARTCOMMIT RESTORE");
    println!();
    println!("Current HEAD:    {}", plan.current_head);
    println!("Checkpoint HEAD: {}", plan.record.original_head);
    println!(
        "Branch:          {}",
        plan.current_branch.as_deref().unwrap_or("(detached)")
    );
    println!();
    println!("Commits that would be removed:");
    for oid in &plan.record.created_commits {
        println!("  {}", short_oid(oid));
    }
    println!();
    println!(
        "Working tree: {}",
        if plan.working_tree_has_changes {
            "has uncommitted changes (staged/unstaged/untracked) — restore does not touch these either way"
        } else {
            "clean"
        }
    );
    println!();
    if plan.is_safe {
        println!("Safety: OK — automatic restore is safe.");
    } else {
        println!("Safety: BLOCKED — automatic restore refused.");
        for reason in &plan.unsafe_reasons {
            println!("  - {reason}");
        }
    }
}

fn run_restore(repo_path: Option<PathBuf>, yes: bool) -> ExitCode {
    let target = match resolve_target(repo_path) {
        Ok(t) => t,
        Err(code) => return code,
    };

    let plan = match plan_restore(&target) {
        Ok(p) => p,
        Err(RestoreError::OperationRecord(OperationRecordError::NotFound)) => {
            println!("No SmartCommit operation found to restore.");
            return ExitCode::FAILURE;
        }
        Err(e) => {
            eprintln!("Could not prepare a restore plan: {e}");
            return ExitCode::FAILURE;
        }
    };

    render_restore_plan(&plan);

    if !plan.is_safe {
        println!();
        println!("Manual recovery instructions, if you're sure this is what you want:");
        println!();
        println!("{}", manual_recovery_instructions(&plan.record));
        return ExitCode::FAILURE;
    }

    if !yes {
        print!("\nRestore to the pre-operation state? [y/N] ");
        let _ = std::io::stdout().flush();
        let mut input = String::new();
        if std::io::stdin().read_line(&mut input).is_err() {
            eprintln!("Could not read confirmation input.");
            return ExitCode::FAILURE;
        }
        let answer = input.trim().to_lowercase();
        if answer != "y" && answer != "yes" {
            println!("Cancelled.");
            return exit_code_cancelled();
        }
    }

    match execute_restore(&target, &plan) {
        Ok(()) => {
            println!();
            println!("Restored to {}.", plan.record.original_head);
            ExitCode::SUCCESS
        }
        Err(e) => {
            eprintln!("Restore failed: {e}");
            ExitCode::FAILURE
        }
    }
}

/// Matches `ARCHITECTURE.md` §29's exact failure report shape:
/// completed / failed / not executed / recovery checkpoint. A full
/// success gets a simpler summary.
fn render_execution_report(report: &ExecutionReport) {
    println!();
    match &report.failure {
        Some(failure) => {
            let total = report.completed.len() + 1 + report.not_attempted.len();
            println!(
                "Execution failed at commit {} of {}.",
                failure.group_index + 1,
                total
            );
            println!();
            if !report.completed.is_empty() {
                println!("Completed:");
                for (i, c) in report.completed.iter().enumerate() {
                    println!("{}. {} ({})", i + 1, c.message, short_oid(&c.commit_oid));
                }
                println!();
            }
            println!("Failed:");
            println!("{}. {}", failure.group_index + 1, failure.message);
            println!("   Reason: {}", failure.reason);
            println!();
            if !report.not_attempted.is_empty() {
                println!("Not executed:");
                for (i, m) in report.not_attempted.iter().enumerate() {
                    println!("{}. {}", failure.group_index + 2 + i, m);
                }
                println!();
            }
            println!("Recovery checkpoint:");
            println!("{}", report.checkpoint_backup_ref);
        }
        None => {
            println!("All commits created successfully.");
            println!();
            for (i, c) in report.completed.iter().enumerate() {
                println!("{}. {} ({})", i + 1, c.message, short_oid(&c.commit_oid));
            }
        }
    }
}

fn short_oid(oid: &str) -> &str {
    &oid[..oid.len().min(7)]
}

/// The user declined the confirmation prompt. Distinct from a
/// validation/repository failure so a caller (or a future script
/// wrapping this CLI) can tell "you said no" apart from "something
/// was wrong."
fn exit_code_cancelled() -> ExitCode {
    ExitCode::from(2)
}

/// Execution stopped partway through — some commits were created,
/// some weren't. Distinct from a total failure (nothing happened)
/// since the repository state has genuinely changed and the person
/// needs to look at the report, not just retry blindly.
fn exit_code_partial_failure() -> ExitCode {
    ExitCode::from(3)
}

fn print_diff_summary(diff: &FileDiff, verbose: bool) {
    if diff.is_binary {
        println!("  Binary file changed");
        return;
    }

    println!("  +{} -{}", diff.additions, diff.deletions);
    println!(
        "  {} hunk{}",
        diff.hunks.len(),
        if diff.hunks.len() == 1 { "" } else { "s" }
    );

    if verbose {
        for hunk in &diff.hunks {
            println!("  {}", hunk.header);
            for line in &hunk.lines {
                match line {
                    DiffLine::Added(text) => println!("  +{text}"),
                    DiffLine::Removed(text) => println!("  -{text}"),
                    DiffLine::Context(text) => println!("   {text}"),
                }
            }
        }
    }
}

fn report_repository_error(err: RepositoryError) -> ExitCode {
    match err {
        RepositoryError::NotARepository(_) => {
            println!("No Git repository found.");
            ExitCode::FAILURE
        }
        RepositoryError::PathNotFound(path) => {
            eprintln!("Path does not exist: {}", path.display());
            ExitCode::FAILURE
        }
        RepositoryError::PathNotAccessible { path, reason } => {
            eprintln!("Path is not accessible: {} ({reason})", path.display());
            ExitCode::FAILURE
        }
        RepositoryError::GitUnavailable(msg) => {
            eprintln!("Unable to run 'git': {msg}");
            eprintln!();
            eprintln!("Possible causes:");
            eprintln!("- git is not installed or not on PATH");
            ExitCode::FAILURE
        }
    }
}

fn report_inspector_error(err: InspectorError) -> ExitCode {
    match err {
        InspectorError::Repository(repo_err) => report_repository_error(repo_err),
        InspectorError::GitUnavailable(msg) => {
            eprintln!("Unable to run 'git': {msg}");
            eprintln!();
            eprintln!("Possible causes:");
            eprintln!("- git is not installed or not on PATH");
            ExitCode::FAILURE
        }
        InspectorError::StatusFailed => {
            eprintln!("Unable to read repository status.");
            eprintln!();
            eprintln!("git status did not complete successfully.");
            ExitCode::FAILURE
        }
    }
}

fn report_staged_changes_error(err: StagedChangesError) -> ExitCode {
    match err {
        StagedChangesError::Repository(repo_err) => report_repository_error(repo_err),
        StagedChangesError::GitUnavailable(msg) => {
            eprintln!("Unable to run 'git': {msg}");
            eprintln!();
            eprintln!("Possible causes:");
            eprintln!("- git is not installed or not on PATH");
            ExitCode::FAILURE
        }
        StagedChangesError::CommandFailed(msg) => {
            eprintln!("Unable to read staged changes.");
            eprintln!();
            eprintln!("Details: {msg}");
            ExitCode::FAILURE
        }
    }
}

